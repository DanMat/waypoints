const LOOKUP: ReadonlyMap<string, Continent> = new Map(
	Object.entries(BY_CONTINENT).flatMap(([continent, codes]) =>
		codes.map((code) => [code, continent as Continent] as const),
	),
);

/** Continent for an ISO alpha-2 country code, or `null` if unknown. */
export function continentForCountry(countryCode: string): Continent | null {
	return LOOKUP.get(countryCode.toUpperCase()) ?? null;
}
